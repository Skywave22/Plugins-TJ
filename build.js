#!/usr/bin/env node
// Builds every provider in src/<id>/ into providers/<id>.js and regenerates manifest.json.
//   node build.js            build all
//   node build.js cinezo     build one
// A provider folder holds:
//   index.js               the Nuvio entry (exports getStreams)
//   nuvio.json             manifest entry: name, description, version, supportedTypes, formats, logo, contentLanguage
//   plugin.skystream.js    (optional) the TJ-Plugins SkyStream plugin it is converted from, embedded as-is
// When a provider's built code changes, its version in nuvio.json is bumped (patch) automatically.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const esbuild = require("esbuild");

const ROOT = __dirname;
const SRC = path.join(ROOT, "src");
const OUT = path.join(ROOT, "providers");
const HASHES = path.join(OUT, ".hashes.json");
const REPO = {
  name: "TJ-Plugins",
  description: "TJ-Plugins providers for Nuvio — Hindi, dubbed, Bollywood and world movies & series.",
  author: "TJ-Plugins",
};
const FACTORY_ARGS = ["manifest", "globalThis", "getPreference", "setPreference", "http_get", "http_post", "http_parallel", "_fetch",
  "MultimediaItem", "Episode", "StreamResult", "Actor", "Trailer", "NextAiring", "crypto", "solveCaptcha", "console",
  "setTimeout", "clearTimeout", "setInterval", "clearInterval"];

// embeds a SkyStream plugin as a factory function: its globals become the factory's arguments
const skystreamPlugin = {
  name: "skystream",
  setup(b) {
    b.onLoad({ filter: /\.skystream\.js$/ }, (args) => {
      const src = fs.readFileSync(args.path, "utf8").replace(/^\uFEFF/, "");
      const pick = (n) => `${n}: typeof ${n} === "function" ? ${n} : undefined`;
      return {
        loader: "js",
        contents: `export default function (${FACTORY_ARGS.join(", ")}) {\n${src}\n;return { ${["getHome", "search", "load", "loadStreams"].map(pick).join(", ")} };\n}\n`,
      };
    });
  },
};

async function buildOne(id, hashes) {
  const dir = path.join(SRC, id);
  const metaPath = path.join(dir, "nuvio.json");
  const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
  const res = await esbuild.build({
    entryPoints: [path.join(dir, "index.js")], bundle: true, write: false, format: "cjs", platform: "neutral",
    target: "es2016",            // async/await → generators: also runs on older Hermes-based Nuvio builds
    minifyWhitespace: true, minifySyntax: true, legalComments: "none", charset: "utf8",
    plugins: [skystreamPlugin], logLevel: "silent",
  });
  let code = res.outputFiles[0].text;
  const digest = crypto.createHash("sha256").update(code).digest("hex").slice(0, 16);
  if (hashes[id] && hashes[id] !== digest) {
    const v = String(meta.version || "1.0.0").split(".").map(Number);
    while (v.length < 3) v.push(0);
    v[2]++;
    meta.version = v.join(".");
    fs.writeFileSync(metaPath, JSON.stringify(meta, null, 2) + "\n");
  }
  hashes[id] = digest;
  code = `// ${meta.name} v${meta.version} — TJ-Plugins provider for Nuvio. GENERATED by build.js from src/${id}/, do not edit.\n` + code;
  fs.writeFileSync(path.join(OUT, id + ".js"), code);
  return { id, meta, kb: (code.length / 1024).toFixed(0) };
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const all = fs.readdirSync(SRC, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_") && fs.existsSync(path.join(SRC, d.name, "nuvio.json")))
    .map((d) => d.name).sort();
  const only = process.argv.slice(2).filter((a) => !a.startsWith("-"));
  const hashes = fs.existsSync(HASHES) ? JSON.parse(fs.readFileSync(HASHES, "utf8")) : {};
  let failed = 0;
  for (const id of all) {
    if (only.length && !only.includes(id)) continue;
    try {
      const r = await buildOne(id, hashes);
      console.log(`✅ ${id}.js v${r.meta.version} (${r.kb} KB)`);
    } catch (e) {
      failed++;
      console.log(`❌ ${id}: ${(e.errors || []).map((x) => x.text + (x.location ? ` (${x.location.file}:${x.location.line})` : "")).join("; ") || e.message}`);
    }
  }
  fs.writeFileSync(HASHES, JSON.stringify(hashes, null, 2) + "\n");
  // manifest: every provider folder, sorted by name
  const scrapers = all.map((id) => {
    const m = JSON.parse(fs.readFileSync(path.join(SRC, id, "nuvio.json"), "utf8"));
    const e = { id, name: m.name, description: m.description, version: m.version, author: REPO.author,
      supportedTypes: m.supportedTypes || ["movie", "tv"], filename: `providers/${id}.js`, enabled: m.enabled !== false };
    for (const k of ["formats", "logo", "contentLanguage", "hasSettings", "supportsExternalPlayer"]) if (m[k] !== undefined) e[k] = m[k];
    return e;
  }).filter((e) => fs.existsSync(path.join(OUT, e.id + ".js")))
    .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));
  const prev = fs.existsSync(path.join(ROOT, "manifest.json")) ? JSON.parse(fs.readFileSync(path.join(ROOT, "manifest.json"), "utf8")) : {};
  const sig = JSON.stringify(scrapers.map((s) => [s.id, s.version]));
  let version = prev.version || "1.0.0";
  if (prev.scrapers && JSON.stringify(prev.scrapers.map((s) => [s.id, s.version])) !== sig) {
    const v = version.split(".").map(Number); v[2] = (v[2] || 0) + 1; version = v.join(".");
  }
  const manifest = { name: REPO.name, version, description: REPO.description, author: REPO.author, scrapers };
  fs.writeFileSync(path.join(ROOT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`📄 manifest.json v${version}: ${scrapers.length} provider(s)`);
  process.exit(failed ? 1 : 0);
})();
